export function resolveLocale(value: string | null): Locale {
  return value && Object.hasOwn(messages, value) ? (value as Locale) : "en";
}
export function localeDirection(locale: Locale) {
  return locale === "fa" || locale === "ar" ? "rtl" : "ltr";
}
